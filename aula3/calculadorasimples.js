let num1 = Number(prompt("num1:"));
let num2 = Number(prompt("num2:"));
let operacão = prompt("operação:");
if (operacão=='+') {
        console.log(num1 + num2)
}
else if (operacão=='-') {
        console.log(num1 - num2)
}
else if (operacão=='*') {

        console.log(num1 * num2)
}
else if (operacão=='/') {
        console.log(num1 * num2)
}